//! DATA-only regressions for the actual private transition/finality helpers.
//! Integers below stand for observations in DATA; none is passed to any Win32
//! operation or represented as native qualification. Real handle/CPython tests
//! must use Root's separately authorized original EditOwner installed fixture.
use super::*;

fn data() -> Box<Metadata> {
    let mut value = Box::<Metadata>::new_uninit();
    // Metadata has only integer/pointer POD fields; no native allocation/call.
    unsafe { value.as_mut_ptr().write_bytes(0, 1); value.assume_init() }
}
fn ready_data(a: &mut Metadata) {
    a.side = 1; a.prepared = 2; a.pid = 11; a.thread = 12;
    a.nonce = [7; 32]; a.attributes_ready = 1;
    for (i, c) in a.channels.iter_mut().enumerate() {
        c.original = (100 + i * 12) as F::HANDLE;
        c.pipe_attempted = 1; c.pipe_returned = 1; c.pipe_ntstatus = F::STATUS_SUCCESS;
        c.pipe_custody = 2; c.pipe_output_seen = 1; c.pipe_output = c.original;
        c.pipe_iosb_seen = 1; c.pipe_iosb_status = F::STATUS_SUCCESS;
        c.pipe_information = PIPE_FILE_CREATED;
        c.client = (104 + i * 12) as F::HANDLE;
        c.event = (108 + i * 12) as F::HANDLE;
        c.claimed = 1; c.state = State::Complete as u32;
        c.operation = 3; c.return_seen = 2; a.inherited[i] = c.client;
    }
}
fn created_data(a: &mut Metadata) {
    ready_data(a);
    a.create_attempted = 1; a.create_returned = 1; a.create_bool = 1;
    a.process.hProcess = 200usize as F::HANDLE; a.process.hThread = 204usize as F::HANDLE;
    a.process.dwProcessId = 21; a.process.dwThreadId = 22;
    // Explicit DATA receipt, never generated by a fake CreateProcess.
    a.create_custody = 2; a.process_original = 1; a.thread_original = 1;
}

#[test]
fn retirement_and_each_original_receipt_revoke_creation() {
    let mut a = data(); ready_data(&mut a);
    assert!(creation_ready(&a)); // conditional DATA predicate, no native admission
    a.startup_retired = 1; assert!(!creation_ready(&a)); a.startup_retired = 0;
    a.attributes_deleted = 2; assert!(!creation_ready(&a)); a.attributes_deleted = 0;
    for i in 0..3 {
        a.channels[i].client_close = 2; assert!(!creation_ready(&a));
        a.channels[i].client_close = 0;
        a.channels[i].original_close = 1; assert!(!creation_ready(&a));
        a.channels[i].original_close = 0;
        a.channels[i].event_close = 3; assert!(!creation_ready(&a));
        a.channels[i].event_close = 0;
        a.channels[i].state = State::Pending as u32; assert!(!creation_ready(&a));
        a.channels[i].state = State::Complete as u32;
    }
    a.create_attempted = 1; assert!(!creation_ready(&a));
}
#[test]
fn original_inheritance_roster_cannot_be_changed() {
    let mut a = data(); ready_data(&mut a);
    for i in 0..3 {
        let original = a.inherited[i];
        a.inherited[i] = null_mut(); assert!(!creation_ready(&a));
        a.inherited[i] = a.channels[(i + 1) % 3].client; assert!(!creation_ready(&a));
        a.inherited[i] = original;
    }
}
#[test]
fn rejected_process_outputs_never_authorize_control_or_ack() {
    let mut a = data(); created_data(&mut a);
    for value in [0usize, usize::MAX, usize::MAX - 1, usize::MAX - 3, usize::MAX - 5] {
        a.process.hProcess = value as F::HANDLE;
        assert!(!admitted_process_outputs(&a));
    }
    a.process.hProcess = a.process.hThread; assert!(!admitted_process_outputs(&a));
    a.process.hProcess = a.channels[0].client; assert!(!admitted_process_outputs(&a));
    a.process.hProcess = 200usize as F::HANDLE;
    a.process.dwProcessId = a.pid; assert!(!admitted_process_outputs(&a));
    a.process.dwProcessId = 21; a.process.dwThreadId = 0;
    assert!(!admitted_process_outputs(&a));
    a.process.dwThreadId = 22;
    // Successful BOOL alone cannot bypass a rejected-output custody receipt.
    a.create_custody = 3; a.process_original = 0; a.thread_original = 0;
    assert!(!process_control_ready(&a)); assert!(!acknowledgement_ready(&a));
    assert!(!no_child_effect(&a)); assert!(!parent_consumers_settled(&a));
}
#[test]
fn precreation_and_repeated_acknowledgements_are_rejected() {
    let a = data();
    assert!(!valid_acknowledgement(&a, &handoff(0, 0, &[0; 32], true)));
    let mut a = data(); created_data(&mut a);
    let ack = handoff(a.pid, a.process.dwProcessId, &a.nonce, true);
    assert!(valid_acknowledgement(&a, &ack));
    for index in [0, 8, 12, 16, 20, 24, 28, 32, 64, 95] {
        let mut wrong = ack; wrong[index] ^= 1;
        assert!(!valid_acknowledgement(&a, &wrong));
    }
    assert!(!valid_acknowledgement(&a, &ack[..95]));
    a.handoff = 1; assert!(!valid_acknowledgement(&a, &ack));
    a.handoff = 0; a.unknown = 1; assert!(!valid_acknowledgement(&a, &ack));
    a.unknown = 0; a.first = BAD_STATE; assert!(!valid_acknowledgement(&a, &ack));
}
#[test]
fn successful_zero_is_complete_not_eof_and_counts_are_bounded() {
    assert_eq!(completed_state(1, 0, 1, 0, 64), State::Complete);
    assert_eq!(completed_state(1, 0, 2, 7, 64), State::Complete); // partial write
    assert_eq!(completed_state(1, 0, 1, 65, 64), State::Unknown);
    assert_eq!(completed_state(0, F::ERROR_IO_INCOMPLETE, 1, 0, 64), State::Pending);
    assert_eq!(completed_state(0, F::ERROR_BROKEN_PIPE, 1, 0, 64), State::Eof);
    assert_eq!(completed_state(0, F::ERROR_BROKEN_PIPE, 2, 0, 64), State::Unknown);
    assert_eq!(completed_state(0, F::ERROR_OPERATION_ABORTED, 1, 0, 64), State::Cancelled);
    assert_eq!(completed_state(0, F::ERROR_NOT_FOUND, 1, 0, 64), State::Unknown);
}
#[test]
fn cancellation_return_cannot_finish_or_replace_the_pending_operation() {
    for (value, error) in [(1, 0), (0, F::ERROR_NOT_FOUND), (0, 5)] {
        let mut a = data();
        let c = &mut a.channels[0];
        c.state = State::Pending as u32; c.operation = 2; c.generation = 19;
        c.requested = 64; c.return_seen = 2;
        c.cancel_attempted = 1; c.cancel_return = value; c.cancel_error = error;
        accept_cancel_result(&mut a, Role::Input);
        let c = &a.channels[0];
        assert_eq!(state(c.state), State::Pending);
        assert_eq!((c.generation, c.operation, c.requested), (19, 2, 64));
        assert!(!known_complete(c)); assert!(!parent_consumers_settled(&a));
        assert_eq!(a.unknown != 0, value == 0 && error != F::ERROR_NOT_FOUND);
    }
}
