#[test]
fn pipe_creation_requests_documented_directional_rights_and_native_flags_only() {
    let required = FS::READ_CONTROL | FS::SYNCHRONIZE | FS::FILE_READ_ATTRIBUTES;
    for role in [Role::Input, Role::Output, Role::Error] {
        let server_data = if role == Role::Input { FS::FILE_WRITE_DATA } else { FS::FILE_READ_DATA };
        let client_data = if role == Role::Input { FS::FILE_READ_DATA } else { FS::FILE_WRITE_DATA };
        assert_eq!(pipe_access(role, false), required | server_data);
        assert_eq!(pipe_access(role, true), required | client_data);
        assert_eq!(pipe_access(role, false) & 3, server_data);
        assert_eq!(pipe_access(role, true) & 3, client_data);
        assert_eq!(pipe_access(role, false) & FS::FILE_APPEND_DATA, 0);
        assert_eq!(pipe_access(role, true) & FS::FILE_APPEND_DATA, 0);
        assert_eq!(pipe_server_share(role),
            if role == Role::Input { FS::FILE_SHARE_READ } else { FS::FILE_SHARE_WRITE });
    }
    assert_eq!(PIPE_FILE_CREATE, 2); assert_eq!(PIPE_FILE_CREATED, 2);
    assert_eq!(PIPE_BYTE_STREAM_TYPE | PIPE_REJECT_REMOTE_CLIENTS, 2); // NOT Win32 flag8
    assert_eq!((PIPE_BYTE_STREAM_MODE, PIPE_QUEUE_OPERATION, PIPE_CREATE_OPTIONS), (0, 0, 0));
    assert_eq!(PIPE_DEFAULT_TIMEOUT_100NS, -500_000); // same50ms pipe default, not an owner clock
}
