#[test]
fn successful_nt_status_needs_created_iosb_and_unique_positive_output() {
    let mut a = data();
    let candidate = 512usize as F::HANDLE; // inert DATA, never given to any syscall
    assert!(admitted_pipe_output(&a, candidate, F::STATUS_SUCCESS, PIPE_FILE_CREATED));
    for invalid in [0usize, usize::MAX, usize::MAX - 1, usize::MAX - 3, usize::MAX - 5] {
        assert!(!admitted_pipe_output(&a, invalid as F::HANDLE, F::STATUS_SUCCESS, PIPE_FILE_CREATED));
    }
    assert!(!admitted_pipe_output(&a, candidate, F::STATUS_PENDING, PIPE_FILE_CREATED));
    assert!(!admitted_pipe_output(&a, candidate, F::STATUS_SUCCESS, 1)); // FILE_OPENED is not FILE_CREATE
    a.channels[0].event = candidate;
    assert!(!admitted_pipe_output(&a, candidate, F::STATUS_SUCCESS, PIPE_FILE_CREATED));
    a.channels[0].event = null_mut(); a.channels[1].client = candidate;
    assert!(!admitted_pipe_output(&a, candidate, F::STATUS_SUCCESS, PIPE_FILE_CREATED));
    a.channels[1].client = null_mut(); a.process.hProcess = candidate;
    assert!(!admitted_pipe_output(&a, candidate, F::STATUS_SUCCESS, PIPE_FILE_CREATED));
}
