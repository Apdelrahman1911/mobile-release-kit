#[test]
fn launch_and_reclamation_require_the_actual_pipe_creation_custody_receipt() {
    let mut a = data(); ready_data(&mut a);
    assert!(creation_ready(&a));
    for i in 0..3 {
        a.channels[i].pipe_custody = 3; assert!(!creation_ready(&a));
        a.channels[i].pipe_custody = 2;
        a.channels[i].pipe_output_seen = 0; assert!(!creation_ready(&a));
        a.channels[i].pipe_output_seen = 1;
        a.channels[i].pipe_iosb_status = F::STATUS_PENDING; assert!(!creation_ready(&a));
        a.channels[i].pipe_iosb_status = F::STATUS_SUCCESS;
        a.channels[i].pipe_information = 1; assert!(!creation_ready(&a));
        a.channels[i].pipe_information = PIPE_FILE_CREATED;
        assert!(!pipe_creation_consumed(&a.channels[i])); // claimed is not closed
        a.channels[i].original_close = 2;
        assert!(pipe_creation_consumed(&a.channels[i]));
        assert!(!creation_ready(&a)); // that positive close permanently revokes create
        a.channels[i].original_close = 0;
    }
}
