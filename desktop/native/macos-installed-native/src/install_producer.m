int mrk_install_producer_step(void *raw,uint32_t phase,mrk_install_producer_report *out) {
#if MRK_INSTALL_PRODUCER_CONFIGURED
    producer_cell *cell=raw;
    if(!original(cell) || !out) return 0;
#if MRK_INSTALL_PRODUCER_SIGNING
    if(sign_role(cell->report.reserved)) return sign_step(cell,phase,out);
#endif
    if(code_role(cell->report.reserved)) return code_step(cell,phase,out);
    if(cell->report.reserved!=0 && cell->report.reserved!=4) return 0;
    if(cell->report.failed || cell->report.unknown || phase<1
        || phase>MRK_INSTALL_PRODUCER_STEPS || phase!=cell->report.phase+1) return 0;
    unsigned slot=phase_slot(phase);
    if(slot<MRK_INSTALL_PRODUCER_SLOTS && (cell->values[slot] || cell->report.states[slot])) return 0;
    if(phase==9 && (cell->values[9] || cell->report.states[9])) return 0;
    cell->report.phase=phase;cell->report.calls++;
    if(slot<MRK_INSTALL_PRODUCER_SLOTS) cell->report.states[slot]=1;
    if(phase==9) cell->report.states[9]=1;
    @try {
        OSStatus status=errSecSuccess;
        switch(phase) {
            case 1:cell->values[0]=CFDataCreate(NULL,mrk_install_producer_leaf_der,sizeof(mrk_install_producer_leaf_der));break;
            case 2:cell->values[1]=CFDataCreate(NULL,mrk_install_producer_issuer_der,sizeof(mrk_install_producer_issuer_der));break;
            case 3:cell->values[2]=CFDataCreate(NULL,mrk_install_producer_root_der,sizeof(mrk_install_producer_root_der));break;
            case 4:case 5:case 6:
                cell->values[slot]=SecCertificateCreateWithData(NULL,(CFDataRef)cell->values[phase-4]);break;
            case 7:cell->values[6]=SecCertificateCopyKey((SecCertificateRef)cell->values[3]);break;
            case 8:cell->values[7]=SecKeyCopyAttributes((SecKeyRef)cell->values[6]);break;
            case 9: {
                CFErrorRef error=NULL;
                CFDataRef key=SecKeyCopyExternalRepresentation((SecKeyRef)cell->values[6],&error);
                cell->values[8]=key;cell->values[9]=error;
                received(cell,9,0);if(cell->values[9]) failed(cell);break;
            }
            case 10:cell->values[10]=SecPolicyCreateBasicX509();break;
            case 11:cell->values[11]=SecPolicyCreateWithProperties(kSecPolicyAppleCodeSigning,NULL);break;
            case 12:cell->values[12]=SecPolicyCreateRevocation(kSecRevocationUseAnyAvailableMethod|kSecRevocationNetworkAccessDisabled);break;
            case 13: {
                const void *values[]={cell->values[3],cell->values[4]};
                cell->values[13]=CFArrayCreate(NULL,values,2,&kCFTypeArrayCallBacks);break;
            }
            case 14: {
                const void *values[]={cell->values[10],cell->values[11],cell->values[12]};
                cell->values[14]=CFArrayCreate(NULL,values,3,&kCFTypeArrayCallBacks);break;
            }
            case 15: {
                const void *values[]={cell->values[5]};cell->values[15]=CFArrayCreate(NULL,values,1,&kCFTypeArrayCallBacks);break;
            }
            case 16: {
                SecTrustRef trust=NULL;
                status=SecTrustCreateWithCertificates(cell->values[13],cell->values[14],&trust);
                cell->values[16]=trust;break;
            }
            case 17:status=SecTrustSetAnchorCertificates((SecTrustRef)cell->values[16],(CFArrayRef)cell->values[15]);break;
            case 18:status=SecTrustSetAnchorCertificatesOnly((SecTrustRef)cell->values[16],true);break;
            case 19:status=SecTrustSetNetworkFetchAllowed((SecTrustRef)cell->values[16],false);break;
            case 20:cell->values[17]=CFDateCreate(NULL,CFAbsoluteTimeGetCurrent());break;
            case 21:status=SecTrustSetVerifyDate((SecTrustRef)cell->values[16],(CFDateRef)cell->values[17]);break;
            case 22: {
                CFErrorRef error=NULL;
                Boolean evaluated=SecTrustEvaluateWithError((SecTrustRef)cell->values[16],&error);
                cell->values[18]=error;
                if(!evaluated || cell->values[18]) failed(cell);break;
            }
            case 23:cell->values[19]=SecTrustCopyCertificateChain((SecTrustRef)cell->values[16]);break;
            case 24:case 25:case 26: {
                CFArrayRef chain=(CFArrayRef)cell->values[19];
                if(!chain || CFGetTypeID(chain)!=CFArrayGetTypeID() || CFArrayGetCount(chain)!=3) { failed(cell);break; }
                CFTypeRef certificate=CFArrayGetValueAtIndex(chain,phase-24);
                if(!certificate || CFGetTypeID(certificate)!=SecCertificateGetTypeID()) { failed(cell);break; }
                cell->values[slot]=SecCertificateCopyData((SecCertificateRef)certificate);break;
            }
            case 27:cell->values[23]=CFDataCreate(NULL,cell->message,cell->message_size);break;
            case 28:cell->values[24]=CFDataCreate(NULL,cell->signature,cell->signature_size);break;
            case 29: {
                CFErrorRef error=NULL;
                Boolean verified=SecKeyVerifySignature((SecKeyRef)cell->values[6],kSecKeyAlgorithmRSASignatureMessagePKCS1v15SHA256,
                    (CFDataRef)cell->values[23],(CFDataRef)cell->values[24],&error);
                cell->values[25]=error;
                if(!verified || cell->values[25]) failed(cell);break;
            }
            default:failed(cell);break;
        }
        if(slot<MRK_INSTALL_PRODUCER_SLOTS) received(cell,slot,phase!=22 && phase!=29);
        if(status!=errSecSuccess) failed(cell);
        if(!cell->report.failed && phase==8 && !key_attributes(cell)) failed(cell);
        if(!cell->report.failed && phase==9) {
            CFDataRef key=(CFDataRef)cell->values[8];
            if(CFGetTypeID(key)!=CFDataGetTypeID() || CFDataGetLength(key)<=0 || CFDataGetLength(key)>16384
                || !sha256_matches(CFDataGetBytePtr(key),(size_t)CFDataGetLength(key),mrk_install_producer_public_key_pkcs1_sha256)) failed(cell);
        }
        if(!cell->report.failed && phase==24 && !data_equal(cell->values[20],mrk_install_producer_leaf_der,sizeof(mrk_install_producer_leaf_der))) failed(cell);
        if(!cell->report.failed && phase==25 && !data_equal(cell->values[21],mrk_install_producer_issuer_der,sizeof(mrk_install_producer_issuer_der))) failed(cell);
        if(!cell->report.failed && phase==26 && !data_equal(cell->values[22],mrk_install_producer_root_der,sizeof(mrk_install_producer_root_der))) failed(cell);
        cell->report.returned++;
        if(phase==29 && !cell->report.failed) cell->report.matched=1;
    } @catch (...) { unknown(cell); }
    *out=cell->report;return 1;
#else
    (void)raw;(void)phase;(void)out;return 0;
#endif
}
