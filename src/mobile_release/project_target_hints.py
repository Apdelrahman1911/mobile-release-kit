"""Passive Xcode app-target names from the existing admitted source inventory.

These are suggestions, not resolved build settings or identity-edit authority.
No new reader, build, scheme inference, source transformation or IO lives here.
"""
from __future__ import annotations

import re
from pathlib import PurePosixPath
from typing import Any, Mapping

from .project_identity import IdentityInputError, need, public_path
from .project_identity_ios import _Project, _atom, _value

MAX_PROJECTS = 16
MAX_TARGETS = 32
MAX_SOURCE_BYTES = 512 * 1024
_NAME = re.compile(r"[A-Za-z0-9_. :()-]{1,255}")
_GENERATED = re.compile(r"(?im)^[ \t]*(?://|/\*|\*)[^\r\n]*(?:generated by|do not edit)")
_CODES = frozenset({"missing-source", "source-limit", "unsupported-source",
                    "ambiguous-target", "generated-project"})


def _project_path(value: object) -> bool:
    return (public_path(value) and value.endswith(".xcodeproj")
            and public_path(value + "/project.pbxproj"))


def valid_ios_app_targets(value: object) -> bool:
    """Closed optional discovery DATA, also admitted by existing setup guidance."""
    if type(value) is not list or len(value) > MAX_PROJECTS:
        return False
    seen: set[str] = set()
    for row in value:
        if (type(row) is not dict or set(row) not in ({"project", "source", "targets"},
                {"project", "source", "targets", "diagnostic"})
                or not _project_path(row["project"]) or row["project"] in seen
                or type(row["source"]) is not str or row["source"] != row["project"] + "/project.pbxproj"):
            return False
        seen.add(row["project"])
        targets, diagnostic = row["targets"], row.get("diagnostic")
        if type(targets) is not list or len(targets) > MAX_TARGETS:
            return False
        names: set[str] = set()
        for target in targets:
            if (type(target) is not dict or set(target) != {"name", "line"}
                    or type(target["name"]) is not str or not _NAME.fullmatch(target["name"])
                    or target["name"] in names or not _line(target["line"])):
                return False
            names.add(target["name"])
        if "diagnostic" in row and (
            type(diagnostic) is not dict or set(diagnostic) != {"code", "line"}
            or type(diagnostic["code"]) is not str or diagnostic["code"] not in _CODES
            or not _line(diagnostic["line"]) or targets
        ):
            return False
    return True


def _line(value: object) -> bool:
    return type(value) is int and 1 <= value <= MAX_SOURCE_BYTES + 1


def ios_app_target_hints(sources: Mapping[str, str], projects: list[str]) -> list[dict[str, Any]]:
    """List only named PBXNativeTarget applications, never a scheme or product.

    The caller owns the finite, no-follow source read. Unsupported projects keep
    an exact source location but no partial name list. Oversized project rosters
    return no suggestions rather than selecting an arbitrary surviving project.
    """
    if type(projects) is not list or len(projects) > MAX_PROJECTS:
        return []
    if any(not _project_path(path) for path in projects) or len(set(projects)) != len(projects):
        return []
    generated = any(PurePosixPath(path).name in {"project.yml", "project.yaml", "Project.swift", "Tuist.swift"}
                    or "Tuist" in PurePosixPath(path).parts for path in sources)
    result: list[dict[str, Any]] = []
    for path in sorted(projects):
        source = path + "/project.pbxproj"
        # The original snapshot drops None members while bounding hints. Omit
        # the optional diagnostic rather than depending on a null surviving it.
        row: dict[str, Any] = {"project": path, "source": source, "targets": []}
        result.append(row)
        text = sources.get(source)
        code, line = None, 1
        if text is None:
            code = "missing-source"
        elif type(text) is not str:
            code = "unsupported-source"
        elif len(text) > MAX_SOURCE_BYTES:
            code = "source-limit"
        else:
            try:
                if len(text.encode("utf-8")) > MAX_SOURCE_BYTES:
                    code = "source-limit"
                elif generated or _GENERATED.search(text):
                    code = "generated-project"
                else:
                    project = _Project(source, text)
                    need(len(project.target_ids) <= 128, "unsupported-syntax", source)
                    names: dict[str, str] = {}
                    targets = []
                    for identifier in project.target_ids:
                        body = project.get(identifier)
                        token = _atom(body.get("name"), source, text)
                        # Native selection matches IDs OR names across ALL
                        # targets. A test/aggregate target can make an app name
                        # ambiguous too, so do not filter before this check.
                        need(token.value not in names and (token.value not in project.target_ids
                             or token.value == identifier), "ambiguous-target", source, text, token.start)
                        names[token.value] = identifier
                        if (_value(body.get("isa"), source) == "PBXNativeTarget"
                                and _value(body.get("productType"), source) == "com.apple.product-type.application"):
                            need(_NAME.fullmatch(token.value) is not None, "unsupported-syntax", source, text, token.start)
                            targets.append({"name": token.value, "line": text.count("\n", 0, token.start) + 1})
                    if len(targets) > MAX_TARGETS:
                        code = "source-limit"
                    else:
                        row["targets"] = sorted(targets, key=lambda target: target["name"])
            except IdentityInputError as error:
                diagnostic = error.diagnostic
                code = "ambiguous-target" if diagnostic.code == "ambiguous-target" else "unsupported-source"
                line = diagnostic.line
            except (UnicodeError, RecursionError):
                code = "unsupported-source"
        if code is not None:
            row["diagnostic"] = {"code": code, "line": line}
    return result
