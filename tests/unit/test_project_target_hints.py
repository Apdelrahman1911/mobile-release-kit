"""Synthetic PBX text and finite passive snapshot fixtures; no build or provider."""
from __future__ import annotations

from contextlib import ExitStack
import copy
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

from mobile_release.project_target_hints import (MAX_PROJECTS, MAX_SOURCE_BYTES,
    ios_app_target_hints, valid_ios_app_targets)
from . import test_project_identity as fixture


class IosAppTargetHintsTests(unittest.TestCase):
    def hints(self, text=None, *, extra=None, projects=None):
        sources = {fixture.PBX: (fixture.pbx(other=True).decode() if text is None else text), **(extra or {})}
        with ExitStack() as stack:
            for target in ("subprocess.Popen", "os.system", "pathlib.Path.open", "mobile_release.discovery.run_owned"):
                stack.enter_context(patch(target, side_effect=AssertionError("Static hint executed or opened a source")))
            result = ios_app_target_hints(sources, projects or [fixture.IOS.project])
        self.assertTrue(valid_ios_app_targets(result))
        self.assertNotIn("DO-NOT-EXPORT-THIS-SCRIPT", json.dumps(result))
        return result

    def test_literal_application_name_not_test_framework_product_or_scheme(self):
        text = fixture.pbx(other=True).decode()
        for product in ("com.apple.product-type.bundle.unit-test", "com.apple.product-type.framework"):
            with self.subTest(product=product):
                source = text.replace("com.apple.product-type.bundle.unit-test", product)
                row = self.hints(source, extra={fixture.SCHEME.replace("Reader.xcscheme", "ReleaseArchive.xcscheme"):
                    fixture.scheme().decode().replace('BlueprintName="Reader"', 'BlueprintName="NotAnAppTarget"')})[0]
                self.assertEqual(row, {"project": fixture.IOS.project, "source": fixture.PBX,
                    "targets": [{"name": "Reader", "line": source[:source.index("name = Reader;")].count("\n") + 1}]})

    def test_multiple_apps_and_projects_remain_separate_explicit_choices(self):
        source = fixture.pbx(other=True).decode().replace("ReaderTests", "SecondApp").replace(
            "com.apple.product-type.bundle.unit-test", "com.apple.product-type.application")
        extra = {"other/Other.xcodeproj/project.pbxproj": fixture.pbx().decode().replace("name = Reader;", "name = OtherApp;")}
        rows = self.hints(source, extra=extra, projects=["other/Other.xcodeproj", fixture.IOS.project])
        self.assertEqual([target["name"] for target in rows[0]["targets"]], ["Reader", "SecondApp"])
        self.assertEqual([target["name"] for target in rows[1]["targets"]], ["OtherApp"])
        self.assertEqual(set(rows[0]), {"project", "source", "targets"})

    def test_duplicate_and_id_alias_names_refuse_whole_project(self):
        source = fixture.pbx(other=True).decode()
        for changed in (source.replace("name = ReaderTests;", "name = Reader;"),
                        source.replace("name = Reader;", f"name = {fixture.IDS['other']};")):
            with self.subTest(source=changed[-40:]):
                row = self.hints(changed)[0]
                self.assertEqual(row["targets"], [])
                self.assertEqual(row["diagnostic"]["code"], "ambiguous-target")
                self.assertGreater(row["diagnostic"]["line"], 1)

    def test_malformed_or_dynamic_source_does_not_leave_partial_names(self):
        source = fixture.pbx(other=True).decode()
        for changed in (source[:-5], source + "{", source.replace("name = Reader;", 'name = "$(APP_TARGET)";'),
                        source.replace(f"rootObject = {fixture.IDS['project']}", "rootObject = MISSING"),
                        source.replace("name = ReaderTests;", "name = ReaderTests; name = Hidden;")):
            with self.subTest(tail=changed[-40:]):
                row = self.hints(changed)[0]
                self.assertEqual(row["targets"], [])
                self.assertEqual(row["diagnostic"]["code"], "unsupported-source")

    def test_missing_and_generated_projects_are_manual_not_guessed_from_scheme(self):
        rows = ios_app_target_hints({fixture.SCHEME: fixture.scheme().decode()}, [fixture.IOS.project])
        self.assertEqual(rows[0]["targets"], [])
        self.assertEqual(rows[0]["diagnostic"], {"code": "missing-source", "line": 1})
        for text, extra in (("// Generated by fixture\n" + fixture.pbx().decode(), {}),
                            (fixture.pbx().decode(), {"project.yml": "targets: {MaybeApp: {type: application}}"})):
            row = self.hints(text, extra=extra)[0]
            self.assertEqual(row["targets"], [])
            self.assertEqual(row["diagnostic"]["code"], "generated-project")

    def test_fixed_limits_refuse_without_truncating_names_or_roster(self):
        self.assertEqual(self.hints(" " * (MAX_SOURCE_BYTES + 1))[0]["diagnostic"]["code"], "source-limit")
        self.assertEqual(ios_app_target_hints({}, [f"App{i}.xcodeproj" for i in range(MAX_PROJECTS + 1)]), [])
        ids = [f"A{i}" for i in range(33)]
        body = "".join(f'{key} = {{ isa = PBXNativeTarget; name = App{i}; productType = "com.apple.product-type.application"; }};'
                       for i, key in enumerate(ids))
        source = '{ objects = { P = {isa = PBXProject; mainGroup = G; targets = (' + ",".join(ids) + ',); };' + body + ' }; rootObject = P; }'
        self.assertEqual(self.hints(source)[0]["diagnostic"]["code"], "source-limit")
        for project in ("../Bad.xcodeproj", "private/Bad.xcodeproj", "/Bad.xcodeproj"):
            self.assertEqual(ios_app_target_hints({}, [project]), [])

    def test_closed_hint_data_never_claims_partial_diagnostic_as_listed(self):
        original = self.hints()
        before = copy.deepcopy(original)
        self.assertTrue(valid_ios_app_targets(original))
        self.assertEqual(original, before)
        variants = []
        for change in ({"unexpected": True}, {"source": "Other.xcodeproj/project.pbxproj"},
                       {"diagnostic": {"code": "unsupported-source", "line": 1}}, {"diagnostic": None},
                       {"targets": [{"name": "Reader", "line": True}]},
                       {"targets": [{"name": "Reader", "line": 1}] * 2}):
            variants.append([{**original[0], **change}])
        variants.extend([original * 2, [original[0]] * 17])
        for value in variants:
            self.assertFalse(valid_ios_app_targets(value))

    def test_actual_discovery_and_setup_guidance_keep_the_additive_hint(self):
        # Root's three-file integration patch is applied to the disposable
        # source projection for this test; missing hooks fail, never skip.
        from mobile_release.discovery import parse_project_sources
        from mobile_release.api._setup_analysis import analyze_setup
        texts = {name: raw.decode() for name, raw in fixture.ios(other=True).items()}
        found = parse_project_sources(texts, [fixture.IOS.project])
        self.assertEqual(found["ios"]["appTargets"], self.hints())
        result = analyze_setup("format-valid", json.loads(fixture.config("ios")), found, partial=False)
        self.assertFalse(result["discoveryPartial"])

    def test_actual_passive_snapshot_retains_app_names_and_normal_setup_analysis(self):
        from mobile_release.api._snapshot import project_snapshot
        with tempfile.TemporaryDirectory(prefix="mrk-target-hints-") as temporary:
            root = Path(temporary)
            for name, raw in fixture.ios(other=True).items():
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(raw)
            with patch("subprocess.Popen", side_effect=AssertionError("No project execution")):
                result = project_snapshot(str(root))
            self.assertFalse(result["discovery"]["partial"])
            self.assertEqual(result["discovery"]["hints"]["ios"]["appTargets"], self.hints())
            self.assertIn("setupAnalysis", result)
            self.assertFalse(result["assurance"]["projectCodeExecuted"])
            self.assertFalse(result["assurance"]["storeContacted"])


if __name__ == "__main__":
    unittest.main()
